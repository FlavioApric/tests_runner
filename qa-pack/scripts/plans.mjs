#!/usr/bin/env node
// S6/S7 execution plans: renders <paths.plans>/*.md from qa.config.json, so every way of running the suite is
// written down once and stays in sync with the config.
//   browser.md   Playwright projects, local run, --shard=i/N with blob reports and merge-reports
//   backend.md   the backend adapter layers (G3)
//   access.md    the access matrix (router adapter) summary
//   mobile.md    + maestro-android.yml   emulator recipe and the GitHub Actions template (only when mobile.enabled)
//   node qa-pack/scripts/plans.mjs [--project <dir>] [--check]
import fs from 'node:fs'
import path from 'node:path'
import { loadConfig, projectDirFrom } from '../lib/config.mjs'
import { loadAdapter } from '../runners/backend.mjs'
import { repoRoot } from './fleet-units.mjs'
import { PACK_DIR, args, read, readJson, write, relTo, render, isMain } from '../lib/util.mjs'

const MAESTRO = { version: '2.11.0', sha256: '5384593cb4e7a106489e75a821d157dd43f4e438df6bc308b72e82c685e1283a' }

function browser(cfg) {
  const pw = cfg.playwright, n = pw.shards ?? 1, c = pw.config
  const proj = pw.projects.map((p) => `| ${p.name} | ${p.device ?? ''} | ${p.use ? JSON.stringify(p.use) : ''} | ${p.grep ?? 'all'} |`)
  return [`# Browser plan (${cfg.project})`, '', 'GENERATED by `qa-pack/scripts/plans.mjs` from qa.config.json. Do not edit.', '',
    '## Projects', '', '| Project | Device | Overrides | grep |', '|---|---|---|---|', ...proj, '',
    '## Local', '', '```bash', `npx playwright test -c ${c}`, `npx playwright test -c ${c} --repeat-each=3 --retries=0   # S6 reliability`, '```', '',
    `## Sharded (${n} shard${n > 1 ? 's' : ''})`, '', 'Each shard writes a blob report (QA_BLOB=1); merge them into one HTML report and one junit file:', '', '```bash',
    ...Array.from({ length: n }, (_, i) => `QA_BLOB=1 npx playwright test -c ${c} --shard=${i + 1}/${n}`),
    'npx playwright merge-reports --reporter=html,junit ./blob-report', '```', '',
    'On the cloud fleet every shard is its own unit (`<step>-i-of-N`), and the blob reports come back in the unit results.', ''].join('\n')
}

async function backend(cfg) {
  const ad = await loadAdapter(cfg)
  const head = [`# Backend plan (${cfg.project})`, '', 'GENERATED by `qa-pack/scripts/plans.mjs`. Do not edit.', '']
  if (!ad) return [...head, 'backend.adapter is `none`: G3 is not applicable.', ''].join('\n')
  const ls = ad.layers(cfg)
  return [...head, `Adapter: \`${cfg.backend.adapter}\` (qa-pack/adapters/backend/${cfg.backend.adapter}.mjs). Local stack only, never production.`, '',
    '| Layer | What | Needs | Files |', '|---|---|---|---|', ...ls.map((l) => `| ${l.name} | ${l.what} | ${l.requires.join(', ')} | ${l.files.length} |`), '',
    '```bash', 'node qa-pack/runners/backend.mjs --project . --layer all', '```', '',
    `A file that still contains \`${cfg.backend.scaffoldMarker}\` is a pending scaffold: the layer is red until it is written.`, ''].join('\n')
}

function access(cfg) {
  const head = [`# Access plan (${cfg.project})`, '', 'GENERATED by `qa-pack/scripts/plans.mjs`. Do not edit.', '']
  if (!cfg.router || cfg.router.adapter === 'none') return [...head, 'No router adapter: the access matrix is not generated.', ''].join('\n')
  const f = cfg.abs('access')
  if (!fs.existsSync(f)) return [...head, `Adapter \`${cfg.router.adapter}\`. Run \`node qa-pack/scripts/access-matrix.mjs\` to build ${cfg.paths.access}.`, ''].join('\n')
  const m = readJson(f), by = {}, keys = m.personas.map((p) => p.key ?? p)
  for (const c of m.cells) (by[`${c.method} ${c.path}`] ??= {})[c.persona] = c.expect
  return [...head, `Adapter \`${m.adapter}\`: ${m.routes.length} route(s) x ${m.personas.length} persona(s) = ${m.cells.length} cell(s). Every cell is replayed by the compiled access spec.`, '',
    `| Route | ${keys.join(' | ')} |`, `|---|${keys.map(() => '---').join('|')}|`, ...Object.entries(by).map(([r, v]) => `| ${r} | ${keys.map((p) => v[p] ?? '').join(' | ')} |`), ''].join('\n')
}

function mobileVars(cfg) {
  const m = cfg.mobile, root = repoRoot(cfg.dir)
  return { PROJECT: cfg.project, API_LEVEL: m.apiLevel ?? 34, TARGET: m.target ?? 'google_apis', PROFILE: m.profile ?? 'pixel_6', AVD: m.avd ?? 'qa_pack_api34',
    MAESTRO_VERSION: m.maestro.version ?? MAESTRO.version, MAESTRO_SHA256: m.maestro.sha256 ?? MAESTRO.sha256, RUNS: m.maestro.runs, OUT: m.maestro.out,
    STACK_UP: cfg.stack.up ?? 'echo "no stack.up in qa.config"', BUILD: m.build ?? 'echo "set qa.config mobile.build"; exit 1', APK: m.apk ?? 'android/app/build/outputs/apk/debug/app-debug.apk',
    APP_ID: m.appId ?? 'APP_ID_NOT_SET', REVERSE_PORTS: (m.reversePorts ?? []).join(' ') || 'none', PACK: relTo(cfg.dir, PACK_DIR), PLANS: cfg.paths.plans,
    PROJECT_DIR: relTo(root, cfg.dir), NODE: cfg.fleet.node }
}

export async function planFiles(cfg) {
  const P = cfg.paths.plans, files = [[`${P}/browser.md`, browser(cfg)], [`${P}/backend.md`, await backend(cfg)], [`${P}/access.md`, access(cfg)]]
  if (cfg.mobile.enabled) {
    const v = mobileVars(cfg)
    files.push([`${P}/mobile.md`, render(read(path.join(PACK_DIR, 'templates', 'mobile', 'EMULATOR.md')), v)])
    files.push([`${P}/maestro-android.yml`, render(read(path.join(PACK_DIR, 'templates', 'github', 'maestro-android.yml')), v)])
  }
  return files
}

if (isMain(import.meta.url)) {
  const a = args(), cfg = loadConfig(projectDirFrom())
  const files = await planFiles(cfg)
  if (a.flag('--check')) {
    const stale = files.filter(([f, t]) => { const p = path.join(cfg.dir, f); return !fs.existsSync(p) || read(p).replace(/\r/g, '') !== t }).map(([f]) => f)
    console.log(stale.length ? `stale: ${stale.join(', ')} (run plans.mjs)` : `plans up to date: ${files.length} file(s)`)
    process.exit(stale.length ? 1 : 0)
  }
  for (const [f, t] of files) write(path.join(cfg.dir, f), t)
  console.log(`plans: ${files.map(([f]) => f).join(', ')}`)
}
