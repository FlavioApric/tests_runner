#!/usr/bin/env node
// S7: the flow -> the qa-fleet contract (<paths.fleet>/units.json, schema qa-fleet/units@1) + unit.sh + charters.
// Every pack.json / flow.extra step with a `fleet.kind` becomes a unit (static | stack | mobile); `fleet.shards: true`
// splits it into playwright.shards units (`--shard=i/N`, blob reports merged by `npx playwright merge-reports`).
// With fleet.explore, one local Claude explorer unit per area (agent + charter; agent units never go to a runner).
// The output is checked against qa-pack/schema/units.schema.json and, when the fleet checkout is reachable
// (QA_FLEET_DIR, with lib/units.mjs), against the fleet's own validateUnits().
//   node qa-pack/scripts/fleet-units.mjs [--project <dir>] [--check]
import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { loadConfig, projectDirFrom } from '../lib/config.mjs'
import { loadFlow } from '../lib/flow.mjs'
import { validate } from '../lib/jsonschema.mjs'
import { PACK_DIR, args, read, readJson, write, relTo, render, isMain } from '../lib/util.mjs'

export const UNITS_SCHEMA = path.join(PACK_DIR, 'schema', 'units.schema.json')
const MAESTRO_DEFAULT = '2.11.0'

export function repoRoot(dir) {
  for (let d = path.resolve(dir); ; d = path.dirname(d)) {
    if (fs.existsSync(path.join(d, '.git'))) return d
    if (path.dirname(d) === d) return path.resolve(dir)
  }
}

const q = (s) => (/^[\w@%+=:,./-]+$/.test(s) ? s : `'${String(s).replace(/'/g, `'\\''`)}'`)
const shellCmd = (argv) => (argv[0] === 'bash' && argv[1] === '-lc' ? argv[2] : argv.map(q).join(' '))

function needsOf(cfg, kind, step) {
  const n = [`node:${cfg.fleet.node}`]
  if (kind !== 'static' && ['docker-compose', 'supabase'].includes(cfg.stack.kind)) n.push('docker')
  if ((step.tags ?? []).includes('browser') || (step.requires ?? []).includes('playwright-browser')) n.push(`browsers:${cfg.playwright.browsers}`)
  if (kind === 'mobile') n.push(`android-emulator:${cfg.mobile.apiLevel ?? 34}`)
  return n
}

export function buildUnits(cfg) {
  const root = repoRoot(cfg.dir), projRel = relTo(root, cfg.dir)
  const inProject = (cmd) => (projRel === '.' ? cmd : `cd ${q(projRel)} && ${cmd}`)
  const atRoot = (p) => (projRel === '.' ? p : `${projRel}/${p}`)
  const results = cfg.fleet.results.map((r) => (r === 'qa-fleet-results' ? r : atRoot(r)))
  const units = []
  for (const s of loadFlow(cfg)) {
    if (!s.fleet?.kind || !s.applies) continue
    const kind = s.fleet.kind, base = { step: s.id, needs: needsOf(cfg, kind, s), tags: [...new Set([kind, ...(s.tags ?? [])])], env: { QAF_KIND: kind } }
    const est = s.fleet.estMinutes ?? (kind === 'static' ? 3 : kind === 'mobile' ? 40 : 15)
    const timeout = s.fleet.timeoutMinutes ?? (kind === 'static' ? 20 : kind === 'mobile' ? 120 : 60)
    const secrets = kind === 'static' ? [] : [...(cfg.fleet.secrets ?? [])]
    const extra = secrets.length ? { secrets } : {}
    const shards = s.fleet.shards ? cfg.playwright.shards : 1
    if (shards > 1) {
      for (let i = 1; i <= shards; i++) units.push({ id: `${s.id}-${i}-of-${shards}`, ...base, cmd: inProject(`${shellCmd(s.argv)} --shard=${i}/${shards}`), estMinutes: est, timeoutMinutes: timeout, results: [...results, atRoot('blob-report')], env: { ...base.env, QA_BLOB: '1' }, ...extra })
    } else units.push({ id: s.id, ...base, cmd: inProject(shellCmd(s.argv)), estMinutes: est, timeoutMinutes: timeout, ...extra })
  }
  if (cfg.fleet.explore) for (const a of cfg.areas) {
    units.push({ id: `explore-${a.id.toLowerCase()}-${a.slug}`, step: 'explore', tags: ['explore', a.id], agent: { charter: relTo(path.dirname(cfg.abs('fleet')), path.join(cfg.abs('fleet'), 'charters', `${a.id}.md`)), mcp: cfg.mobile.enabled ? ['playwright', 'mobile'] : ['playwright'] } })
  }
  const doc = { schema: 'qa-fleet/units@1', project: cfg.project, '//': 'GENERATED by `node qa-pack/runners/pack.mjs fleet-units` from qa.config.json + qa-pack/pack.json. Do not edit: change the config and regenerate.', defaults: { results, env: { CI: '1' } }, units }
  return { doc, projRel, root }
}

export function unitSh(cfg, projRel) {
  const m = cfg.mobile, setup = cfg.fleet.setup ?? {}
  const up = cfg.stack.up ? `( cd "$PROJECT_DIR" && ${cfg.stack.up} ) || infra "stack up"${cfg.stack.preflight ? `\n  ( cd "$PROJECT_DIR" && ${cfg.stack.preflight} ) || fail "stack preflight"` : ''}` : ': # stack.kind ' + cfg.stack.kind + ': the Playwright webServer starts the app'
  return render(read(path.join(PACK_DIR, 'templates', 'fleet', 'unit.sh')), {
    PROJECT: cfg.project, PROJECT_DIR: projRel, MAESTRO_VERSION: m.maestro.version ?? MAESTRO_DEFAULT, MAESTRO_SHA256: m.maestro.sha256 ?? '',
    SETUP_STATIC: setup.static ?? 'npm ci --no-audit --no-fund', SETUP_STACK: setup.stack ?? 'npm ci --no-audit --no-fund && npx playwright install --with-deps chromium', STACK_UP: up,
    SETUP_MOBILE: setup.mobile ?? m.build ?? 'echo "set qa.config mobile.build"; exit 1', REVERSE_PORTS: (m.reversePorts ?? []).join(' ') || ':', APK_GLOB: m.apk ?? 'android/app/build/outputs/apk/debug/*.apk', APP_ID: m.appId ?? 'APP_ID_NOT_SET',
  })
}

export function charters(cfg) {
  const tpl = read(path.join(PACK_DIR, 'templates', 'fleet', 'charter.md'))
  return cfg.areas.map((a) => ({ file: `${cfg.paths.fleet}/charters/${a.id}.md`, text: render(tpl, { AREA_ID: a.id, AREA_TITLE: a.title, PROJECT: cfg.project, PREVIEW_URL: cfg.preview.url, AREA_FOCUS: a.focus ? ` Focus: ${a.focus}` : '', REQUIREMENTS: cfg.paths.requirements, CASES: cfg.paths.cases, COMPILED: cfg.paths.compiled, COVERAGE: cfg.paths.coverage, PERSONAS: cfg.personas.map((p) => `${p.key} (${p.role})`).join(', ') }) }))
}

export async function validateUnitsDoc(doc) {
  const errors = validate(readJson(UNITS_SCHEMA), doc).map((e) => `schema: ${e}`)
  const fleetDir = process.env.QA_FLEET_DIR
  let fleet = 'not checked (set QA_FLEET_DIR to a tests_runner main checkout)'
  if (fleetDir && fs.existsSync(path.join(fleetDir, 'lib', 'units.mjs'))) {
    const { validateUnits } = await import(pathToFileURL(path.join(fleetDir, 'lib', 'units.mjs')).href)
    errors.push(...validateUnits(doc).map((e) => `fleet: ${e}`)); fleet = 'checked with the fleet validateUnits()'
  }
  return { errors, fleet }
}

export async function fleetFiles(cfg) {
  const { doc, projRel } = buildUnits(cfg)
  const files = [[`${cfg.paths.fleet}/units.json`, JSON.stringify(doc, null, 1) + '\n'], [`${cfg.paths.fleet}/unit.sh`, unitSh(cfg, projRel)]]
  if (cfg.fleet.explore) for (const c of charters(cfg)) files.push([c.file, c.text])
  return { doc, files, ...(await validateUnitsDoc(doc)) }
}

if (isMain(import.meta.url)) {
  const a = args(), cfg = loadConfig(projectDirFrom())
  const { doc, files, errors, fleet } = await fleetFiles(cfg)
  errors.forEach((e) => console.log(`error: ${e}`))
  if (a.flag('--check')) {
    const stale = files.filter(([f, t]) => { const p = path.join(cfg.dir, f); return !fs.existsSync(p) || read(p).replace(/\r/g, '') !== t }).map(([f]) => f)
    console.log(stale.length ? `stale: ${stale.join(', ')} (run pack.mjs fleet-units)` : `fleet units up to date: ${doc.units.length} unit(s); fleet validation ${fleet}`)
    process.exit(stale.length || errors.length ? 1 : 0)
  }
  if (errors.length) { console.log('nothing written'); process.exit(1) }
  for (const [f, t] of files) write(path.join(cfg.dir, f), t)
  try { fs.chmodSync(path.join(cfg.dir, cfg.paths.fleet, 'unit.sh'), 0o755) } catch {}
  console.log(`fleet units: ${doc.units.length} (${doc.units.filter((u) => u.agent).length} local explorer) -> ${cfg.paths.fleet}/units.json; fleet validation ${fleet}`)
}
